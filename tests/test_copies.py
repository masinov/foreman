"""``docs/STATUS.md``, ``docs/sprints/current.md`` and a finished sprint's archive copy,
written by Foreman from its database (ADR-0040 section 2)."""

from __future__ import annotations

from contextlib import redirect_stderr, redirect_stdout
from datetime import datetime, timezone
import io
from pathlib import Path
import subprocess
import tempfile
import unittest

from foreman.cli import main
from foreman.domain.models import Project, Sprint, Task
from foreman.domain.settings import ProjectSettings, SettingsError
from foreman.engine.sprints import SprintFlow
from foreman.history.records import RunRecords
from foreman.mutations import Mutations
from foreman.mutations.copies import archive_path, render_current, render_status, sprint_number
from foreman.notifications.delivery import NotificationDispatcher
from foreman.store import ForemanStore

STATUS = "docs/STATUS.md"
CURRENT = "docs/sprints/current.md"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", *args], cwd=repo, check=True, capture_output=True, text=True).stdout.strip()


class CopiesTests(unittest.TestCase):
    def setUp(self) -> None:
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        root = Path(temp.name)
        self.repo = root / "repo"
        (self.repo / "docs" / "sprints").mkdir(parents=True)
        for args in (("init", "-q"), ("checkout", "-q", "-b", "main"),
                     ("config", "user.email", "t@example.com"), ("config", "user.name", "T")):
            git(self.repo, *args)
        (self.repo / ".gitignore").write_text(".foreman/\n", encoding="utf-8")
        (self.repo / STATUS).write_text("old hand-written status\n", encoding="utf-8")
        (self.repo / CURRENT).write_text("old hand-written sprint\n", encoding="utf-8")
        git(self.repo, "add", ".")
        git(self.repo, "commit", "-q", "-m", "init")
        self.store = ForemanStore(root / "foreman.db")
        self.store.initialize()
        self.addCleanup(self.store.close)

    def project(self, **settings: object) -> Project:
        project = Project(id="p", name="P", repo_path=str(self.repo), workflow_id="development",
                          default_branch="main", settings=dict(settings))
        self.store.save_project(project)
        return project

    def sprints(self) -> tuple[Sprint, Sprint]:
        one = Sprint(id="s1", project_id="p", title="Sprint 7: weight of evidence", goal="Rank the claims.",
                     status="active", order_index=0, started_at="2026-11-20T10:00:00+00:00")
        two = Sprint(id="s2", project_id="p", title="Sprint 8: sources", goal="Cite them.", status="planned", order_index=1)
        self.store.save_sprint(one)
        self.store.save_sprint(two)
        first = Task(id="t1", sprint_id="s1", project_id="p", title="Claim card", status="done", task_key="P-1")
        second = Task(id="t2", sprint_id="s1", project_id="p", title="Rank | order", status="todo", task_key="P-2",
                      order_index=1, depends_on_task_ids=["t1", "t3"])
        third = Task(id="t3", sprint_id="s1", project_id="p", title="Source link", status="blocked", task_key="P-3",
                     order_index=2, blocked_reason="needs a decision")
        for task in (first, second, third):
            self.store.save_task(task)
        self.store.save_task(Task(id="t4", sprint_id="s2", project_id="p", title="Cite", task_key="P-4"))
        return one, two

    def resolve_tasks(self) -> None:
        for task in self.store.list_tasks(sprint_id="s1"):
            task.status = "done"
            self.store.save_task(task)

    def text(self, path: str) -> str:
        return (self.repo / path).read_text(encoding="utf-8")

    def test_current_describes_the_active_sprint_with_what_each_task_waits_for(self) -> None:
        project = self.project()
        self.sprints()
        text = render_current(self.store, project)
        self.assertIn("## Sprint 7: weight of evidence", text)
        self.assertIn("Rank the claims.", text)
        self.assertIn("| P-1 | Claim card | nothing | done |", text)
        # P-1 is done, so only P-3 is waited for; the pipe in a title does not break the table.
        self.assertIn("| P-2 | Rank \\| order | P-3 | todo |", text)
        self.assertIn("| P-3 | Source link | blocked: needs a decision | blocked |", text)
        self.assertIn("Generated by Foreman", text)

    def test_current_says_none_is_active_and_which_comes_next(self) -> None:
        project = self.project()
        one, _ = self.sprints()
        one.status = "completed"
        one.completed_at = "2026-11-22T10:00:00+00:00"
        self.store.save_sprint(one)
        text = render_current(self.store, project)
        self.assertIn("No sprint is active.", text)
        self.assertIn("## Next: Sprint 8: sources", text)
        self.assertIn("| P-4 | Cite |", text)

    def test_status_names_the_sprints_what_is_blocked_and_the_schema(self) -> None:
        project = self.project()
        one, _ = self.sprints()
        done = Sprint(id="s0", project_id="p", title="Sprint 6: earlier", status="completed", order_index=-1,
                      completed_at="2026-11-19T10:00:00+00:00")
        self.store.save_sprint(done)
        self.store.save_task(Task(id="t0", sprint_id="s0", project_id="p", title="Old", status="done", task_key="P-0"))
        text = render_status(self.store, project)
        self.assertIn(f"Schema version: {self.store.schema_version()}.", text)
        self.assertIn("Sprint 7: weight of evidence (started 2026-11-20)", text)
        self.assertIn("- P-3 Source link: blocked. needs a decision", text)
        self.assertIn("- Sprint 6: earlier, finished 2026-11-19: 1 of 1 tasks done", text)
        self.assertIn("- Sprint 8: sources", text)

    def test_a_sprint_starting_writes_the_copies_in_a_commit_of_their_own(self) -> None:
        self.project(generate_copies=True)
        one, two = self.sprints()
        one.status = "completed"
        one.completed_at = "2026-11-22T10:00:00+00:00"
        self.store.save_sprint(one)
        before = git(self.repo, "rev-parse", "main")
        Mutations(self.store, via="cli").transition_sprint(self.store.get_sprint("s2"), "active")
        head = git(self.repo, "rev-parse", "main")
        self.assertEqual(git(self.repo, "rev-parse", f"{head}^"), before)
        self.assertIn("Sprint 8: sources", git(self.repo, "log", "-1", "--format=%s"))
        self.assertIn("## Sprint 8: sources", self.text(CURRENT))
        self.assertIn("Sprint 8: sources (started", self.text(STATUS))
        (event,) = self.store.list_sprint_events("s2", event_types=["engine.copies_written"])
        self.assertEqual(event.payload["paths"], [STATUS, CURRENT])
        self.assertEqual(git(self.repo, "status", "--porcelain"), "")

    def test_the_engine_starting_the_next_sprint_writes_them_too(self) -> None:
        project = self.project(generate_copies=True, sprint_completion="auto")
        one, _ = self.sprints()
        self.resolve_tasks()
        records = RunRecords(self.store, NotificationDispatcher(self.store))
        flow = SprintFlow(self.store, records, lambda: datetime(2026, 11, 23, 12, tzinfo=timezone.utc))
        self.assertIsNone(flow.resolve(project, one))
        self.assertEqual(self.store.get_sprint("s2").status, "active")
        self.assertIn("## Sprint 8: sources", self.text(CURRENT))

    def test_a_finished_sprint_writes_the_copies_and_its_archive_in_the_checkpoint_commit(self) -> None:
        self.project(generate_copies=True)
        one, _ = self.sprints()
        self.resolve_tasks()
        before = git(self.repo, "rev-parse", "main")
        Mutations(self.store, via="cli").transition_sprint(self.store.get_sprint("s1"), "completed")
        (event,) = self.store.list_sprint_events("s1", event_types=["engine.checkpoint"])
        head = git(self.repo, "rev-parse", "main")
        self.assertEqual(git(self.repo, "rev-parse", f"{head}^"), before)
        self.assertEqual(git(self.repo, "rev-parse", f"{event.payload['tag']}^{{commit}}"), head)
        archive = "docs/sprints/archive/sprint-7-weight-of-evidence.md"
        self.assertEqual(
            set(git(self.repo, "show", "--name-only", "--format=", head).splitlines()), {STATUS, CURRENT, archive}
        )
        text = self.text(archive)
        self.assertIn("## Sprint 7: weight of evidence", text)
        self.assertIn("Rank the claims.", text)
        self.assertIn("| P-1 | Claim card | done |", text)
        self.assertIn(f"checkpoint, tag `{event.payload['tag']}`", text)
        self.assertIn("No sprint is active.", self.text(CURRENT))
        self.assertIn("Sprint 7: weight of evidence, finished", self.text(STATUS))

    def test_the_command_writes_them_and_the_archive_of_a_named_sprint(self) -> None:
        self.project(generate_copies=True)
        one, _ = self.sprints()
        one.status = "completed"
        one.completed_at = "2026-11-22T10:00:00+00:00"
        self.store.save_sprint(one)
        out = io.StringIO()
        with redirect_stdout(out):
            code = main(["copies", "p", "--sprint", "s1", "--db", str(self.store.db_path)])
        self.assertEqual(code, 0, out.getvalue())
        self.assertIn("archive copy", out.getvalue())
        self.assertTrue((self.repo / archive_path(one)).is_file())
        self.assertIn("## Next: Sprint 8: sources", self.text(CURRENT))
        again = io.StringIO()
        with redirect_stdout(again):
            self.assertEqual(main(["copies", "p", "--sprint", "s1", "--db", str(self.store.db_path)]), 0)
        self.assertIn("up to date", again.getvalue())

    def test_a_project_that_does_not_turn_it_on_is_left_as_it_is(self) -> None:
        self.project()
        self.sprints()
        self.resolve_tasks()
        before = git(self.repo, "rev-parse", "main")
        mutations = Mutations(self.store, via="cli")
        mutations.transition_sprint(self.store.get_sprint("s1"), "completed")
        mutations.transition_sprint(self.store.get_sprint("s2"), "active")
        self.assertEqual(git(self.repo, "rev-parse", "main"), before)
        self.assertEqual(self.text(STATUS), "old hand-written status\n")
        err = io.StringIO()
        with redirect_stderr(err):
            self.assertEqual(main(["copies", "p", "--db", str(self.store.db_path)]), 1)
        self.assertIn("generate_copies=true", err.getvalue())

    def test_copies_that_cannot_be_committed_are_recorded_and_the_tree_is_left_clean(self) -> None:
        self.project(generate_copies=True)
        self.sprints()
        self.resolve_tasks()
        hook = self.repo / ".git" / "hooks" / "pre-commit"
        hook.write_text("#!/bin/sh\necho no commits today >&2\nexit 1\n", encoding="utf-8")
        hook.chmod(0o755)
        before = git(self.repo, "rev-parse", "main")
        Mutations(self.store, via="cli").transition_sprint(self.store.get_sprint("s1"), "completed")
        self.assertEqual(self.store.get_sprint("s1").status, "completed")
        (event,) = self.store.list_sprint_events("s1", event_types=["engine.checkpoint_failed"])
        self.assertIn("no commits today", event.payload["reason"])
        self.assertEqual(git(self.repo, "rev-parse", "main"), before)
        self.assertEqual(self.text(STATUS), "old hand-written status\n")
        self.assertFalse((self.repo / archive_path(self.store.get_sprint("s1"))).exists())

    def test_archive_names(self) -> None:
        self.assertEqual(sprint_number(Sprint(id="a", project_id="p", title="Sprint 60b: engine findings")), "60b")
        self.assertEqual(
            archive_path(Sprint(id="a", project_id="p", title="Sprint 60b: engine findings")),
            "docs/sprints/archive/sprint-60b-engine-findings.md",
        )
        self.assertEqual(
            archive_path(Sprint(id="a", project_id="p", title="Review Phase 0 correctness")),
            "docs/sprints/archive/sprint-review-phase-0-correctness.md",
        )

    def test_the_setting_is_true_or_false(self) -> None:
        self.assertFalse(ProjectSettings.from_raw({}).generate_copies)
        self.assertTrue(ProjectSettings.from_raw({"generate_copies": True}).generate_copies)
        with self.assertRaises(SettingsError):
            ProjectSettings.from_raw({"generate_copies": "yes"})


if __name__ == "__main__":
    unittest.main()
