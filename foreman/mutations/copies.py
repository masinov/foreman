"""Readable copies of what Foreman's database holds (ADR-0040 section 2).

``docs/STATUS.md`` says where the project is, ``docs/sprints/current.md``
describes the active sprint (or the next one), ``docs/sprints/backlog.md``
lists the work filed and accepted and not yet in a sprint, and a finished
sprint gets an archive copy, ``docs/sprints/archive/sprint-<n>-<slug>.md``,
written from its record (ADR-0037). No task edits them: Foreman writes the
first two when a sprint starts, all of them when it finishes (in the
checkpoint's commit) and from ``foreman copies``. The owner's directions are
not a copy: they are files of their own in ``docs/directions/``. Every file says it is generated, and nothing in it
changes unless the database does, so writing twice leaves no commit.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
import re

from ..domain.models import Event, Project, Sprint, Task
from ..repo.git import run_git
from ..store import ForemanStore

STATUS_FILE = "docs/STATUS.md"
CURRENT_FILE = "docs/sprints/current.md"
BACKLOG_FILE = "docs/sprints/backlog.md"
DIRECTIONS_DIR = "docs/directions"
ARCHIVE_DIR = "docs/sprints/archive"

#: How many finished sprints STATUS.md lists.
RECENT_FINISHED = 5

_NOTICE = (
    "<!-- Generated by Foreman from its database. Do not edit: the next "
    "sprint start or finish, or `foreman copies`, writes it again. -->"
)
_BACKLOG_NOTICE = (
    "<!-- Generated by Foreman from its database. Do not edit: when a sprint finishes, "
    "and from `foreman copies`, it is written again. -->"
)


@dataclass(frozen=True, slots=True)
class CopyFile:
    """One file to write: its path in the repository and its text."""

    path: str
    text: str


def _day(moment: str | None) -> str:
    if not moment:
        return "not yet"
    try:
        parsed = datetime.fromisoformat(moment.replace("Z", "+00:00"))
    except ValueError:
        return moment
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return f"{parsed.astimezone(timezone.utc):%Y-%m-%d}"


def _cell(text: str) -> str:
    return " ".join((text or "").split()).replace("|", "\\|")


def _key(task: Task) -> str:
    return task.task_key or task.id


def _task_order(task: Task) -> tuple[int, str]:
    return (task.order_index, task.created_at)


def sprint_number(sprint: Sprint) -> str | None:
    """The number in a title such as ``Sprint 60b: engine findings``, or None."""

    match = re.match(r"^\s*sprint\s+(\d+[a-z]?)\b", sprint.title or "", re.IGNORECASE)
    return match.group(1).lower() if match else None


def _slug(text: str, limit: int = 48) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:limit].rstrip("-")


def archive_path(sprint: Sprint) -> str:
    """``docs/sprints/archive/sprint-65-the-method-second-part.md``."""

    title = sprint.title or sprint.id
    number = sprint_number(sprint)
    rest = re.sub(r"^\s*sprint\s+\d+[a-z]?\s*[:\-—–]?\s*", "", title, flags=re.IGNORECASE) if number else title
    slug = _slug(rest) or _slug(sprint.id) or "sprint"
    name = f"sprint-{number}-{slug}" if number else f"sprint-{slug}"
    return f"{ARCHIVE_DIR}/{name}.md"


class _Facts:
    """What the copies are written from, read once from the store."""

    def __init__(self, store: ForemanStore, project: Project) -> None:
        self.store = store
        self.project = project
        self.sprints = store.list_sprints(project.id)
        self._tasks: dict[str, list[Task]] = {}

    def tasks(self, sprint: Sprint) -> list[Task]:
        if sprint.id not in self._tasks:
            self._tasks[sprint.id] = sorted(self.store.list_tasks(sprint_id=sprint.id), key=_task_order)
        return self._tasks[sprint.id]

    @property
    def keys(self) -> dict[str, str]:
        found: dict[str, str] = {}
        for sprint in self.sprints:
            for task in self.tasks(sprint):
                found[task.id] = _key(task)
        return found

    @property
    def active(self) -> Sprint | None:
        return next((s for s in self.sprints if s.status == "active"), None)

    @property
    def planned(self) -> list[Sprint]:
        return [s for s in self.sprints if s.status == "planned"]

    @property
    def finished(self) -> list[Sprint]:
        done = [s for s in self.sprints if s.status == "completed"]
        return sorted(done, key=lambda s: s.completed_at or "", reverse=True)


def _state(task: Task) -> str:
    if task.status == "blocked":
        return "blocked"
    if task.paused_at:
        return f"{task.status.replace('_', ' ')}, paused"
    if task.status == "in_progress" and task.workflow_current_step:
        return f"in progress, at {task.workflow_current_step}"
    return task.status.replace("_", " ")


def _waits_for(task: Task, facts: _Facts, by_id: dict[str, Task]) -> str:
    waits: list[str] = []
    for dep_id in task.depends_on_task_ids:
        dep = by_id.get(dep_id)
        label = facts.keys.get(dep_id, dep_id)
        if dep is None or dep.status not in ("done", "cancelled"):
            waits.append(label)
    if task.status == "blocked" and task.blocked_reason:
        waits.append(f"blocked: {task.blocked_reason}")
    return "; ".join(waits) or "nothing"


def _task_table(tasks: list[Task], facts: _Facts, *, waits: bool = True) -> list[str]:
    if not tasks:
        return ["No tasks."]
    by_id = {task.id: task for task in tasks}
    for sprint in facts.sprints:
        for other in facts.tasks(sprint):
            by_id.setdefault(other.id, other)
    if waits:
        lines = ["| Key | Task | Waits for | State |", "|-----|------|-----------|-------|"]
        for task in tasks:
            lines.append(
                f"| {_cell(_key(task))} | {_cell(task.title)} | {_cell(_waits_for(task, facts, by_id))} | {_state(task)} |"
            )
    else:
        lines = ["| Key | Task | State |", "|-----|------|-------|"]
        for task in tasks:
            lines.append(f"| {_cell(_key(task))} | {_cell(task.title)} | {_state(task)} |")
    return lines


def render_current(store: ForemanStore, project: Project) -> str:
    """``docs/sprints/current.md``: the active sprint, or which one comes next."""

    facts = _Facts(store, project)
    active = facts.active
    parts = ["# Current Sprint", "", _NOTICE, ""]
    if active is not None:
        tasks = facts.tasks(active)
        parts += [
            f"## {active.title}",
            "",
            f"- Status: active, started {_day(active.started_at)}",
            f"- Tasks: {sum(t.status == 'done' for t in tasks)} of {len(tasks)} done",
        ]
        block = store.get_sprint_block(active.id)
        if block is not None:
            parts.append(f"- Blocked: {block.reason}")
        parts += ["", "### Goal", "", (active.goal or "No goal is set.").strip(), "", "### Tasks", ""]
        parts += _task_table(tasks, facts)
        parts += ["", "The full description and acceptance criteria of each task are in Foreman.", ""]
        return "\n".join(parts)
    parts += ["No sprint is active.", ""]
    planned = facts.planned
    if planned:
        nxt = planned[0]
        tasks = facts.tasks(nxt)
        parts += [f"## Next: {nxt.title}", "", f"- Status: planned, {len(tasks)} tasks", "", "### Goal", ""]
        parts += [(nxt.goal or "No goal is set.").strip(), "", "### Tasks", ""]
        parts += _task_table(tasks, facts)
        if len(planned) > 1:
            parts += ["", "### Then", ""] + [f"- {s.title}" for s in planned[1:]]
        parts.append("")
    else:
        parts += ["No sprint is planned. Plan one from the backlog.", ""]
    return "\n".join(parts)


def render_status(store: ForemanStore, project: Project) -> str:
    """``docs/STATUS.md``: where the project is, from the database."""

    facts = _Facts(store, project)
    parts = [
        "# STATUS",
        "",
        _NOTICE,
        "",
        f"Project: {project.name}. Default branch: {project.default_branch}. "
        f"Schema version: {store.schema_version()}.",
        "",
        "## Active sprint",
        "",
    ]
    active = facts.active
    if active is None:
        parts.append("None is active.")
        if facts.planned:
            parts.append(f"Next in the queue: {facts.planned[0].title}.")
    else:
        tasks = facts.tasks(active)
        counts = ", ".join(
            f"{sum(t.status == status for t in tasks)} {status.replace('_', ' ')}"
            for status in ("done", "in_progress", "todo", "blocked", "cancelled")
            if any(t.status == status for t in tasks)
        )
        parts.append(f"{active.title} (started {_day(active.started_at)}): {counts or 'no tasks'}.")
        if active.goal:
            parts += ["", active.goal.strip()]
        parts += ["", "The tasks are in `docs/sprints/current.md`."]
    parts += ["", "## Held or blocked", ""]
    held: list[str] = []
    for block in store.list_level_blocks():
        if block.project_id not in (None, project.id):
            continue
        what = "The workspace" if block.scope == "workspace" else f"Sprint {block.scope_id}"
        held.append(f"- {what} is blocked: {block.reason}")
    for sprint in facts.sprints:
        for task in facts.tasks(sprint):
            if sprint.status in ("completed", "cancelled"):
                continue
            if task.status == "blocked":
                held.append(f"- {_key(task)} {task.title}: blocked. {task.blocked_reason or 'No reason is recorded.'}")
            elif task.paused_at:
                held.append(f"- {_key(task)} {task.title}: paused ({task.pause_mode or 'finish_step'}).")
    parts += held or ["Nothing is held or blocked."]
    parts += ["", "## Last finished sprints", ""]
    finished = facts.finished[:RECENT_FINISHED]
    if not finished:
        parts.append("None yet.")
    for sprint in finished:
        tasks = facts.tasks(sprint)
        done = sum(t.status == "done" for t in tasks)
        tag = _checkpoint_tag(store, sprint)
        suffix = f", tag `{tag}`" if tag else ""
        parts.append(f"- {sprint.title}, finished {_day(sprint.completed_at)}: {done} of {len(tasks)} tasks done{suffix}.")
    planned = facts.planned
    if planned:
        parts += ["", "## Planned", ""] + [f"- {s.title}" for s in planned]
    parts += [
        "",
        "## Where the rest is",
        "",
        "- How things work and what was decided: `docs/guide/`, `docs/adr/`.",
        "- Conflicts between the spec, the design and the code: `docs/guide/conflicts-spec-design-code.md`.",
        "- Direction: `docs/ROADMAP.md`; the owner's directions, one file each: `docs/directions/`.",
        "- Open work: Foreman's backlog, copied to `docs/sprints/backlog.md`.",
        "- What changed: `CHANGELOG.md`.",
        "",
    ]
    return "\n".join(parts)


def render_backlog(store: ForemanStore, project: Project) -> str:
    """``docs/sprints/backlog.md``: the filed and accepted work, by priority, with its keys."""

    tasks, _, counts = store.page_backlog_tasks(project.id, statuses=["triage", "todo"])
    filed = [t for t in tasks if t.status == "triage"]
    accepted = [t for t in tasks if t.status == "todo"]
    parts = [
        "# Backlog",
        "",
        _BACKLOG_NOTICE,
        "",
        "The work filed in Foreman's backlog and not yet in a sprint, by priority "
        "(a lower number first), as it was when this file was last written. "
        "File, accept, decline and plan work in Foreman (`foreman backlog`, or the project's Backlog tab).",
        "",
        f"The owner's directions and the design decisions taken with the owner are not tasks. "
        f"They are one file each in [`{DIRECTIONS_DIR}/`](../directions/README.md).",
        "",
        f"Filed {counts['triage']}, accepted {counts['todo']}.",
        "",
    ]
    for heading, group in (("Filed, not accepted", filed), ("Accepted, not planned", accepted)):
        parts += [f"## {heading} ({len(group)})", ""]
        if not group:
            parts += ["None.", ""]
            continue
        parts += ["| Key | Task | Type | Priority | Filed by | Filed |", "|-----|------|------|----------|----------|-------|"]
        for task in group:
            parts.append(
                f"| {_cell(_key(task))} | {_cell(task.title)} | {task.task_type} | {task.priority} "
                f"| {_cell(task.created_by or '')} | {_day(task.created_at)} |"
            )
        parts.append("")
    return "\n".join(parts)


def _checkpoint_tag(store: ForemanStore, sprint: Sprint) -> str | None:
    for event in reversed(store.list_sprint_events(sprint.id, event_types=["engine.checkpoint"])):
        if event.payload.get("completed_at") == sprint.completed_at and event.payload.get("tag"):
            return str(event.payload["tag"])
    return None


def _record_line(event: Event) -> str | None:
    payload = event.payload
    when = _day(event.timestamp)
    if event.event_type == "engine.sprint_started":
        return f"- {when}: the sprint started."
    if event.event_type == "engine.sprint_completed":
        return f"- {when}: the engine finished the sprint."
    if event.event_type == "engine.sprint_ready":
        return f"- {when}: every task was resolved; the sprint waited for a person to finish it."
    if event.event_type == "engine.checkpoint":
        tag = payload.get("tag")
        sha = str(payload.get("sha") or "")[:7]
        return f"- {when}: checkpoint, tag `{tag}` at {sha}."
    if event.event_type == "engine.checkpoint_failed":
        return f"- {when}: the checkpoint failed: {payload.get('reason')}."
    return None


def render_archive(store: ForemanStore, project: Project, sprint: Sprint, *, tag: str | None = None) -> str:
    """A finished sprint's archive copy, from its tasks and its record (ADR-0037)."""

    facts = _Facts(store, project)
    tasks = facts.tasks(sprint)
    done = [t for t in tasks if t.status == "done"]
    cancelled = [t for t in tasks if t.status == "cancelled"]
    number = sprint_number(sprint)
    parts = [
        f"# {'Sprint ' + number + ' (archived)' if number else 'Sprint (archived)'}",
        "",
        _NOTICE,
        "",
        f"## {sprint.title}",
        "",
        f"- Id: `{sprint.id}`",
        f"- Started: {_day(sprint.started_at)}",
        f"- Finished: {_day(sprint.completed_at)}",
        f"- Tasks: {len(done)} done, {len(cancelled)} cancelled, {len(tasks)} in all",
        "",
        "### Goal",
        "",
        (sprint.goal or "No goal was set.").strip(),
        "",
        "### Tasks",
        "",
    ]
    parts += _task_table(tasks, facts, waits=False)
    record = [line for event in store.list_sprint_events(sprint.id) if (line := _record_line(event))]
    if tag and not any("checkpoint, tag" in line for line in record):
        # The checkpoint's own record is written after this file, in the same step.
        record.append(f"- {_day(sprint.completed_at)}: checkpoint, tag `{tag}`.")
    parts += ["", "### Record", ""] + (record or ["The sprint's record holds no events."])
    parts.append("")
    return "\n".join(parts)


def render_copies(
    store: ForemanStore,
    project: Project,
    *,
    finished: Sprint | None = None,
    tag: str | None = None,
    backlog: bool = False,
) -> list[CopyFile]:
    """The files to write: STATUS and current, the backlog's copy when asked, and ``finished``'s archive copy."""

    files = [
        CopyFile(STATUS_FILE, render_status(store, project)),
        CopyFile(CURRENT_FILE, render_current(store, project)),
    ]
    if backlog:
        files.append(CopyFile(BACKLOG_FILE, render_backlog(store, project)))
    if finished is not None and not finished.is_backlog:
        files.append(CopyFile(archive_path(finished), render_archive(store, project, finished, tag=tag)))
    return files


def stage_copies(root: Path, files: list[CopyFile]) -> tuple[list[str], list[Path]]:
    """Write the files that differ from what ``root`` holds, and ``git add`` them.

    Returns the paths changed and the files that did not exist before, so a
    commit that fails can put the tree back.
    """

    changed: list[str] = []
    created: list[Path] = []
    for file in files:
        target = root / file.path
        existing = target.read_text(encoding="utf-8") if target.is_file() else None
        if existing == file.text:
            continue
        if existing is not None and file.path.startswith(f"{ARCHIVE_DIR}/") and "Generated by Foreman" not in existing:
            # A sprint file written by hand before the copies existed is kept.
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        if existing is None:
            created.append(target)
        target.write_text(file.text, encoding="utf-8")
        run_git(root, "add", "--", file.path)
        changed.append(file.path)
    return changed, created
